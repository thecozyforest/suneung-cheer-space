function hash(s) {
  let h = 2166136261;
  for (const ch of String(s)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

/**
 * 오늘의 문구 목록. examDays: 수능까지 남은 날(daysUntil 결과).
 * 수능 뒤에는 전 학년 쉼 문구, 당일에는 당일 문구.
 */
export function todayPool(dow, examDays) {
  if (examDays < 0) return { name: '모두의 쉼', lines: AFTER_EXAM };
  if (examDays === 0) return { name: '수능 당일', lines: EXAM_DAY };
  return DAY_POOLS[dow];
}

/** 날짜로 정해지는 오늘의 첫 문구 (같은 날 같은 방에서는 모두 같은 문구로 시작) */
export function phraseOfDay(lines, ymd, salt = '') {
  return lines[hash(`${ymd}|${salt}`) % lines.length];
}

/** 방금 본 문구를 피해 다음 문구 */
export function nextPhrase(lines, last, rand = Math.random) {
  if (lines.length < 2) return lines[0];
  let p;
  do { p = lines[Math.floor(rand() * lines.length)]; } while (p === last);
  return p;
}

export function allPhraseCount() {
  return Object.values(DAY_POOLS).reduce((n, p) => n + p.lines.length, 0) + EXAM_DAY.length + AFTER_EXAM.length
    + Object.values(ROOM_POOLS).reduce((n, l) => n + l.length, 0);
}
